def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", default="docs/tracker/plan.yaml")
    ap.add_argument("--out", help="write PLAN.md, PROGRESS.md, REMAINING.md, FUTURE.md here")
    ap.add_argument("--summary", action="store_true", help="print a short status")
    ap.add_argument("--fetch", action="store_true", help="git fetch main, team-context and tags first")
    ap.add_argument("--evidence", help="read evidence from this JSON file instead of git/gh (tests)")
    ap.add_argument("--now", help="ISO time instead of the current time (tests)")
    ap.add_argument("--strict", action="store_true",
                    help="exit 1, writing nothing, if any evidence source failed (the workflow: keep the last good tracker)")
    ap.add_argument("--check", action="store_true", help="validate the plan only")
    ap.add_argument("--self_test", action="store_true")
    ap.add_argument("--count_runs", nargs="+", metavar="OUT_ROOT", help="count finished runs per block")
    a = ap.parse_args()
    if a.self_test:
        self_test()
        return 0
    if a.count_runs:
        print(count_runs(a.count_runs))
        return 0
    plan = load_plan(a.plan)
    errors = check_plan(plan)
    if errors:
        sys.exit("plan errors:\n  " + "\n  ".join(errors))
    if a.check:
        print("plan ok: %d tasks, %d rubric items, %d prospects" % (
            len(plan["tasks"]), len(plan.get("rubric", [])), len(plan.get("prospects", []))))
        return 0
    now = parse_time(a.now) if a.now else datetime.datetime.now(IST)
    if a.evidence:
        with open(a.evidence) as f:
            ev = json.load(f)
        ev.setdefault("warnings", [])
    else:
        ev = collect_evidence(plan, a.fetch)
    if a.strict and ev.get("warnings"):
        sys.exit("evidence incomplete, nothing written:\n  " + "\n  ".join(ev["warnings"]))
    tasks, runs, lines = evaluate(plan, ev, now)
    if a.out:
        os.makedirs(a.out, exist_ok=True)
        for name, text in (("PLAN.md", write_plan_md(plan, tasks, now, ev)),
                           ("PROGRESS.md", write_progress_md(plan, tasks, runs, lines, now, ev)),
                           ("REMAINING.md", write_remaining_md(plan, tasks, now, ev)),
                           ("FUTURE.md", write_future_md(plan, tasks, now, ev)),
                           ("README.md", write_index_md(plan, tasks, runs, now))):
            with open(os.path.join(a.out, name), "w") as f:
                f.write(text + "\n")
    if a.summary or not a.out:
        print(summary(plan, tasks, runs, now))
    return 0


if __name__ == "__main__":
    sys.exit(main())
