def summary(plan, tasks, runs, now):
    left = [t for t in tasks.values() if t["status"] != "done"]
    over = sorted((t for t in left if t["status"] == "overdue"), key=lambda t: t["due_t"])
    nxt = sorted((t for t in left if t["status"] != "overdue"), key=lambda t: t["due_t"])[:6]
    out = ["Tracker %s IST: %.0f %% done (planned by now %.0f %%); Aayush %.0f %%, Disha %.0f %%; runs %s" % (
        fmt_time(now), pct(tasks), planned_pct(tasks, now),
        pct(tasks, lambda t: t["owner"] in ("aayush", "both")), pct(tasks, lambda t: t["owner"] in ("disha", "both")),
        " ".join("%s=%d/%d" % (b, runs.get(b, 0), n) for b, n in plan["blocks"].items()))]
    out += ["OVERDUE %s %s (%s, due %s)" % (t["id"], t["title"], t["owner"], fmt_time(t["due_t"])) for t in over]
    out += ["next    %s %s (%s, due %s)" % (t["id"], t["title"], t["owner"], fmt_time(t["due_t"])) for t in nxt]
    ready = [p["id"] for p in prospect_status(plan, tasks, now) if p["status"].startswith("READY")]
    out.append("prospects ready to adopt: " + (", ".join(ready) or "none"))
    return "\n".join(out)


def count_runs(roots):
    counts = {}
    for root in roots:
        block = RUN_ROOTS.get(os.path.basename(os.path.normpath(root)))
        if block is None:
            sys.exit("%s: folder name must be one of %s" % (root, ", ".join(RUN_ROOTS)))
        counts[block] = len(glob.glob(os.path.join(root, "llff_*v", "*", "*", "seed*", "metrics.json")))
    return "runs " + " ".join("%s=%d" % kv for kv in sorted(counts.items()))


