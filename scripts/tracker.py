#!/usr/bin/env python3
"""Project tracker: plan -> progress, remaining work, future prospects (docs/tracker/plan.yaml).

    python3 scripts/tracker.py --fetch --summary                  # what's done and what's next, right now
    python3 scripts/tracker.py --fetch --out <dir>                # write PLAN.md PROGRESS.md REMAINING.md FUTURE.md
    python3 scripts/tracker.py --count_runs <outputs> [<outputs_pass> ...]   # the "runs" part of a Tracker line
    python3 scripts/tracker.py --check | --self_test              # used by scripts/check.sh

Status is never typed into the plan. It comes from evidence:
  * merged PRs (gh), tags (git ls-remote), files on origin/main;
  * the **Tracker:** line in each context file on origin/team-context, written by that person's agent:
        - **Tracker:** done AY-01..03, AY-05, EXP-N; partial AY-04; working AY-12; runs T1=40 P=0
    "done" and "partial" lists are cumulative; "runs" counts the runs that person (their Colab/Kaggle/A100 shards)
    finished per block, and the two files are summed. Ranges: AY-01..03 or AY-01–03.
.github/workflows/tracker.yml runs this every hour and publishes the four files on the `tracker` branch.
Python 3.7 compatible.
"""
import argparse
import datetime
import glob
import json
import os
import re
import subprocess
import sys

import yaml

IST = datetime.timezone(datetime.timedelta(hours=5, minutes=30))
OWNERS = ("aayush", "disha", "both")
CONTEXT_FILES = {"aayush": "aayush_context.md", "disha": "disha_context.md"}
RANGE = re.compile(r"^(AY|DS)-(\d+)(?:\.\.|–)(\d+)$")
NOT_DONE = re.compile(r"\b(pending|todo|to do|blocked|not|next|waiting)\b")
DONE_ID = re.compile(r"\b((?:AY|DS)-\d{2})(?:\s*(?:–|\.\.)\s*(\d{2})\b)?")
RUN_ROOTS = {"outputs": "T1", "outputs_pass": "P", "outputs_dose": "G", "outputs_noise": "N", "outputs_views": "V"}
GENERATED = "_Generated by `scripts/tracker.py` from `docs/tracker/plan.yaml` and the evidence. Don't edit; change the plan in a PR._"


def run(cmd):
    p = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True)
    return p.returncode, p.stdout


def parse_time(s):
    t = datetime.datetime.fromisoformat(str(s))
    return t if t.tzinfo else t.replace(tzinfo=IST)


def fmt_time(t):
    return t.astimezone(IST).strftime("%a %d %b %H:%M")


# ---------------------------------------------------------------- plan

def load_plan(path):
    with open(path) as f:
        plan = yaml.safe_load(f)
    for t in plan["tasks"]:
        t.setdefault("deps", [])
        t.setdefault("done_when", [])
        t.setdefault("weight", 1)
    return plan


def check_plan(plan):
    errors = []
    ids = [t["id"] for t in plan["tasks"]]
    known = set(ids)
    phases = {p["id"] for p in plan["phases"]}
    for i in sorted(set(x for x in ids if ids.count(x) > 1)):
        errors.append("duplicate task id " + i)
    for t in plan["tasks"]:
        where = "task " + t["id"]
        for key in ("owner", "phase", "due", "title"):
            if key not in t:
                errors.append("%s: missing %s" % (where, key))
        if t.get("owner") not in OWNERS:
            errors.append("%s: owner must be one of %s" % (where, OWNERS))
        if t.get("phase") not in phases:
            errors.append("%s: unknown phase %r" % (where, t.get("phase")))
        try:
            parse_time(t.get("due"))
        except (TypeError, ValueError):
            errors.append("%s: bad due %r" % (where, t.get("due")))
        errors += ["%s: unknown dep %s" % (where, d) for d in t["deps"] if d not in known]
        for cond in t["done_when"]:
            bad = set(cond) - {"pr", "prs", "tag", "file", "runs"}
            if bad or len(cond) != 1:
                errors.append("%s: bad done_when %r" % (where, cond))
                continue
            prs = [cond["pr"]] if "pr" in cond else cond.get("prs")
            if prs is not None and (not isinstance(prs, list) or not prs or
                                    not all(isinstance(n, int) and not isinstance(n, bool) for n in prs)):
                errors.append("%s: pr/prs must be PR numbers (at least one): %r" % (where, cond))
            if "runs" in cond:
                r = cond["runs"] if isinstance(cond["runs"], dict) else {}
                if r.get("block") not in plan["blocks"]:
                    errors.append("%s: unknown run block %r" % (where, r.get("block")))
                if not isinstance(r.get("n"), int) or r.get("n", 0) <= 0:
                    errors.append("%s: runs.n must be a positive integer: %r" % (where, cond))
    for r in plan.get("rubric", []):
        errors += ["rubric %r: unknown task %s" % (r["item"], x) for x in r["tasks"] if x not in known]
        if r["level"] not in ("minimum", "expected", "advanced"):
            errors.append("rubric %r: bad level" % r["item"])
    for p in plan.get("prospects", []):
        errors += ["prospect %s: unknown requirement %s" % (p["id"], x) for x in p["requires"] if x not in known]
        try:
            parse_time(p.get("latest_start"))
        except (TypeError, ValueError):
            errors.append("prospect %s: bad latest_start %r" % (p["id"], p.get("latest_start")))
    if not errors:   # deps must form a DAG
        deps = {t["id"]: t["deps"] for t in plan["tasks"]}
        state = {}

        def visit(n, stack):
            if state.get(n) == 1:
                errors.append("dependency cycle: " + " -> ".join(stack + [n]))
                return
            if state.get(n) == 2:
                return
            state[n] = 1
            for d in deps[n]:
                visit(d, stack + [n])
            state[n] = 2
        for n in deps:
            visit(n, [])
    return errors


# ---------------------------------------------------------------- evidence

def collect_evidence(plan, fetch):
    ev = {"merged_prs": [], "tags": [], "files": [], "context": {}, "warnings": []}
    if fetch:
        rc, _ = run(["git", "fetch", "-q", "origin", "main", "team-context", "--tags"])
        if rc:
            ev["warnings"].append("git fetch failed; using the refs already present")
    rc, out = run(["git", "ls-remote", "--tags", "origin"])
    if rc == 0:
        ev["tags"] = sorted({l.split("refs/tags/")[1].replace("^{}", "") for l in out.splitlines() if "refs/tags/" in l})
    else:
        ev["warnings"].append("could not list tags on origin")
    rc, out = run(["git", "ls-tree", "-r", "--name-only", "origin/main"])
    ev["files"] = out.splitlines() if rc == 0 else []
    if rc:
        ev["warnings"].append("origin/main not available; file evidence skipped")
    for who, name in CONTEXT_FILES.items():
        rc, out = run(["git", "show", "origin/team-context:" + name])
        ev["context"][who] = out if rc == 0 else ""
        if rc:
            ev["warnings"].append("origin/team-context:%s not readable" % name)
    rc, out = run(["gh", "pr", "list", "--repo", plan["repo"], "--state", "merged", "--limit", "500",
                   "--json", "number"])
    if rc == 0:
        ev["merged_prs"] = sorted(x["number"] for x in json.loads(out or "[]"))
    else:
        ev["warnings"].append("gh pr list failed (no gh or no token): PR evidence missing")
    return ev


def expand(token, known):
    m = RANGE.match(token)
    if m:
        pre, a, b = m.group(1), int(m.group(2)), int(m.group(3))
        width = len(m.group(2))
        return ["%s-%0*d" % (pre, width, k) for k in range(a, b + 1)]
    return [token] if token in known else []


def parse_tracker_line(text, known):
    """The **Tracker:** line of one context file -> {done, partial, working: set, runs: {block: n}, found: bool}."""
    res = {"done": set(), "partial": set(), "working": set(), "runs": {}, "found": False, "unknown": [],
           "fallback": False}
    for line in text.splitlines():
        if "**Tracker:**" not in line:
            continue
        res["found"] = True
        for seg in line.split("**Tracker:**", 1)[1].split(";"):
            words = seg.replace(",", " ").split()
            if not words:
                continue
            key, vals = words[0].lower(), words[1:]
            if key == "runs":
                for v in vals:
                    if "=" in v:
                        b, n = v.split("=", 1)
                        if n.strip().isdigit():
                            res["runs"][b.strip()] = int(n)
            elif key in ("done", "partial", "working"):
                for v in vals:
                    ids = expand(v.strip(".()"), known)
                    if ids:
                        res[key].update(ids)
                    else:
                        res["unknown"].append(v)
        break
    if not res["found"]:   # until the person adds a Tracker line: the free-text "**Done ...:**" Status line
        for line in text.splitlines():
            if line.lstrip("- ").startswith("**Done"):
                for m in DONE_ID.finditer(line):
                    ids = expand(m.group(1) + (".." + m.group(2) if m.group(2) else ""), known)
                    rest = re.split(r"[,;]", line[m.end():], 1)[0].lower()
                    if NOT_DONE.search(rest):
                        continue
                    res["partial" if "part" in rest else "done"].update(ids)
                res["fallback"] = True
                break
    return res


# ---------------------------------------------------------------- status

def evaluate(plan, ev, now):
    known = {t["id"] for t in plan["tasks"]}
    lines = {who: parse_tracker_line(txt, known) for who, txt in ev["context"].items()}
    runs = {}
    for res in lines.values():
        for b, n in res["runs"].items():
            runs[b] = runs.get(b, 0) + n
    merged, tags, files = set(ev["merged_prs"]), set(ev["tags"]), set(ev["files"])
    tasks = {}
    for t in plan["tasks"]:
        p, src = 0.0, []
        for cond in t["done_when"]:
            if "pr" in cond or "prs" in cond:
                prs = cond.get("prs") or [cond["pr"]]
                q = sum(1 for n in prs if n in merged) / float(len(prs))
                if q:
                    src.append("PR " + ", ".join("#%d" % n for n in prs if n in merged))
            elif "tag" in cond:
                q = 1.0 if cond["tag"] in tags else 0.0
                if q:
                    src.append("tag " + cond["tag"])
            elif "file" in cond:
                q = 1.0 if cond["file"] in files else 0.0
                if q:
                    src.append(cond["file"])
            else:
                r = cond["runs"]
                q = min(1.0, runs.get(r["block"], 0) / float(r["n"]))
                if q:
                    src.append("%s runs %d/%d" % (r["block"], runs.get(r["block"], 0), r["n"]))
            p = max(p, q)
        working = False
        for who, res in lines.items():
            if t["id"] in res["done"]:
                p = 1.0
                src.append("marked done by " + who)
            elif t["id"] in res["partial"]:
                p = max(p, 0.5)
                src.append("partial (" + who + ")")
            working = working or t["id"] in res["working"]
        tasks[t["id"]] = dict(t, progress=p, source="; ".join(src), working=working, due_t=parse_time(t["due"]))
    for t in tasks.values():
        blockers = [d for d in t["deps"] if tasks[d]["progress"] < 1]
        t["blockers"] = blockers
        if t["progress"] >= 1:
            t["status"] = "done"
        elif t["due_t"] < now:
            t["status"] = "overdue"
        elif t["progress"] > 0 or t["working"]:
            t["status"] = "in progress"
        elif blockers:
            t["status"] = "blocked"
        else:
            t["status"] = "ready"
    return tasks, runs, lines


def pct(tasks, sel=lambda t: True):
    ts = [t for t in tasks.values() if sel(t)]
    w = sum(t["weight"] for t in ts)
    return 100.0 * sum(t["weight"] * t["progress"] for t in ts) / w if w else 100.0


def planned_pct(tasks, now, sel=lambda t: True):
    ts = [t for t in tasks.values() if sel(t)]
    w = sum(t["weight"] for t in ts)
    return 100.0 * sum(t["weight"] for t in ts if t["due_t"] <= now) / w if w else 100.0


def bar(p, n=20):
    k = int(round(p / 100.0 * n))
    return "`" + "█" * k + "░" * (n - k) + "` %3.0f %%" % p


def critical_path(tasks, goal):
    """Longest chain of unfinished tasks that ends at `goal` (by number of tasks)."""
    memo = {}

    def longest(n):
        if n in memo:
            return memo[n]
        best = []
        for d in tasks[n]["deps"]:
            if tasks[d]["progress"] < 1:
                c = longest(d)
                if len(c) > len(best):
                    best = c
        memo[n] = best + [n]
        return memo[n]
    return longest(goal) if tasks[goal]["progress"] < 1 else []


def prospect_status(plan, tasks, now):
    overdue = [t for t in tasks.values() if t["status"] == "overdue"]
    out = []
    for p in plan.get("prospects", []):
        unmet = [r for r in p["requires"] if tasks[r]["progress"] < 1]
        latest = parse_time(p["latest_start"])
        if p["id"] in tasks:
            st = "ADOPTED (%s)" % tasks[p["id"]]["status"]
        elif now > latest:
            st = "PUBLICATION PATH (window passed)"
        elif unmet:
            st = "WAITING for " + ", ".join(unmet)
        elif overdue:
            st = "ON HOLD: %d overdue tasks first" % len(overdue)
        else:
            st = "READY to adopt"
        out.append(dict(p, status=st, latest_t=latest))
    return out


# ---------------------------------------------------------------- reports

def header(plan, now, ev, title):
    s = ["# %s" % title, "", "**%s** · as of %s IST · submit %s IST" % (
        plan["project"], fmt_time(now), fmt_time(parse_time(plan["submit"]))), "", GENERATED, ""]
    for w in ev.get("warnings", []):
        s.append("> ⚠ " + w)
    if ev.get("warnings"):
        s.append("")
    return s


def task_row(t):
    who = {"aayush": "Aayush", "disha": "Disha", "both": "Both"}[t["owner"]]
    return "| %s | %s | %s | %s | %s |" % (t["id"], t["title"], who, fmt_time(t["due_t"]), t["status"])


def write_plan_md(plan, tasks, now, ev):
    s = header(plan, now, ev, "Plan")
    s += ["The full study design is in [docs/PLAN_V2.md](https://github.com/%s/blob/main/docs/PLAN_V2.md); "
          "this is its task list with the current dates." % plan["repo"], ""]
    s += ["**Experiment blocks:** " + ", ".join("%s %d runs" % kv for kv in plan["blocks"].items()), ""]
    for ph in plan["phases"]:
        s += ["## " + ph["name"], "", "| ID | Task | Owner | Due | Depends on | Done when |", "| --- | --- | --- | --- | --- | --- |"]
        for t in sorted((t for t in tasks.values() if t["phase"] == ph["id"]), key=lambda t: t["due_t"]):
            dw = "; ".join(", ".join("%s %s" % kv for kv in c.items()) for c in t["done_when"]) or "marked done"
            s.append("| %s | %s | %s | %s | %s | %s |" % (t["id"], t["title"], t["owner"], fmt_time(t["due_t"]),
                                                         ", ".join(t["deps"]) or "—", dw))
        s.append("")
    return "\n".join(s)


def write_progress_md(plan, tasks, runs, lines, now, ev):
    s = header(plan, now, ev, "Progress")
    total, planned = pct(tasks), planned_pct(tasks, now)
    s += ["## Overall", "", "| | Done | Planned by now |", "| --- | --- | --- |",
          "| **Whole plan** | %s | %3.0f %% |" % (bar(total), planned)]
    for who in ("aayush", "disha"):
        sel = lambda t, w=who: t["owner"] in (w, "both")
        s.append("| %s | %s | %3.0f %% |" % (who.capitalize(), bar(pct(tasks, sel)), planned_pct(tasks, now, sel)))
    for ph in plan["phases"]:
        sel = lambda t, p=ph["id"]: t["phase"] == p
        s.append("| %s | %s | %3.0f %% |" % (ph["name"], bar(pct(tasks, sel)), planned_pct(tasks, now, sel)))
    gap = planned - total
    s += ["", ("**Schedule: behind by %.0f points.** " % gap if gap > 0.5 else "**Schedule: on track.** ")
          + "%d tasks overdue." % sum(1 for t in tasks.values() if t["status"] == "overdue"), ""]
    s += ["## Experiment runs", "", "| Block | Runs | |", "| --- | --- | --- |"]
    for b, n in plan["blocks"].items():
        s.append("| %s | %d / %d | %s |" % (b, runs.get(b, 0), n, bar(100.0 * min(1.0, runs.get(b, 0) / float(n)), 12)))
    s += ["", "## Rubric coverage (professor's expectations)", "",
          "| Level | Expectation | Delivered by | Done |", "| --- | --- | --- | --- |"]
    for level in ("minimum", "expected", "advanced"):
        items = [r for r in plan.get("rubric", []) if r["level"] == level]
        for r in items:
            p = sum(tasks[x]["progress"] for x in r["tasks"]) / float(len(r["tasks"])) if r["tasks"] else 0.0
            s.append("| %s | %s | %s | %3.0f %% |" % (level, r["item"], ", ".join(r["tasks"]) or "**gap**", 100 * p))
    s += ["", "## Completed", "", "| ID | Task | Owner | Evidence |", "| --- | --- | --- | --- |"]
    for t in sorted((t for t in tasks.values() if t["status"] == "done"), key=lambda t: t["due_t"]):
        s.append("| %s | %s | %s | %s |" % (t["id"], t["title"], t["owner"], t["source"]))
    s += ["", "## Tracker lines read", ""]
    for who, res in lines.items():
        state = "found" if res["found"] else ("**missing**: read the free-text Done line instead; add a `**Tracker:**` "
                                              "line to the Status block" if res["fallback"] else "**missing**")
        s.append("- %s: %s" % (who.capitalize(), state)
                 + ("; unknown IDs ignored: " + ", ".join(res["unknown"]) if res["unknown"] else ""))
    return "\n".join(s)


def write_remaining_md(plan, tasks, now, ev):
    s = header(plan, now, ev, "Remaining")
    left = sorted((t for t in tasks.values() if t["status"] != "done"), key=lambda t: t["due_t"])
    soon = now + datetime.timedelta(hours=48)
    groups = [("Overdue", [t for t in left if t["status"] == "overdue"]),
              ("Due in the next 48 hours", [t for t in left if t["status"] != "overdue" and t["due_t"] <= soon]),
              ("Later", [t for t in left if t["due_t"] > soon])]
    for name, ts in groups:
        s += ["## %s (%d)" % (name, len(ts)), ""]
        if ts:
            s += ["| ID | Task | Owner | Due | Status |", "| --- | --- | --- | --- | --- |"] + [task_row(t) for t in ts]
        else:
            s.append("Nothing.")
        s.append("")
    waits = {}
    for t in left:
        for d in t["blockers"]:
            if not tasks[d]["blockers"]:   # only blockers that can be worked on now
                waits.setdefault(tasks[d]["owner"], {}).setdefault(d, []).append(t["id"])
    s += ["## Who is waiting on whom (blocking tasks that can start now)", ""]
    for who, ds in sorted(waits.items()):
        for d, ts in sorted(ds.items()):
            s.append("- **%s** must finish **%s** (%s) to unblock %s" % (who.capitalize(), d, tasks[d]["title"], ", ".join(ts)))
    goal = "SUBMIT" if "SUBMIT" in tasks else left[-1]["id"] if left else None
    path = critical_path(tasks, goal) if goal else []
    s += ["", "## Critical path to %s" % goal, ""]
    s.append(" → ".join("%s (%s, %s)" % (n, tasks[n]["owner"], fmt_time(tasks[n]["due_t"])) for n in path) or "Done.")
    for who in ("aayush", "disha"):
        mine = [t for t in left if t["owner"] in (who, "both")]
        s += ["", "## %s's list (%d)" % (who.capitalize(), len(mine)), ""]
        s += ["- [ ] **%s** %s, due %s%s" % (t["id"], t["title"], fmt_time(t["due_t"]),
                                             " (blocked by %s)" % ", ".join(t["blockers"]) if t["blockers"] else "")
              for t in mine]
    return "\n".join(s)


def write_future_md(plan, tasks, now, ev):
    s = header(plan, now, ev, "Future prospects")
    s += ["Extras we add only if there is time, and the publication path after the course (PLAN_V2 §11). "
          "**READY** means its requirements are done, nothing is overdue and its start window is open: "
          "to adopt it, copy it into `tasks` in `docs/tracker/plan.yaml` (docs-only PR).", ""]
    s += ["| ID | Prospect | Value | Cost | Start by | Status |", "| --- | --- | --- | --- | --- | --- |"]
    for p in prospect_status(plan, tasks, now):
        s.append("| %s | %s<br>_%s_ | %s | %s | %s | **%s** |" % (p["id"], p["title"], p["why"], p["value"], p["cost"],
                                                                 fmt_time(p["latest_t"]), p["status"]))
    return "\n".join(s)


